"""
PREFACE-DBN: Recorded experiment-run dataset format.

Why this module exists
----------------------
Evaluation and data collection must be separate steps. Previously
`36_evaluate_goal6.py` generated its own anomaly signals with
`np.random.normal()` and scored the model on them in the same process, which
measures the generator rather than the system.

A recorded run is the boundary between the two: a fault experiment writes one
JSON file per run containing the *real* per-tick anomaly signals produced by
the Rectifier + autoencoder, plus the ground truth (was a fault injected, when,
and into which service). The evaluator then replays those files. This makes the
evaluation reproducible without a live cluster, and keeps the model strictly
downstream of the data.

Format (one JSON file per run)
------------------------------
{
  "run_id":           "cpu_train_01",
  "source":           "live" | "synthetic",
  "is_positive":      true,
  "t_fault":          15,                  # tick index, null for healthy runs
  "injected_service": "ts-train-service",  # null for healthy runs
  "services":         ["ts-ui-dashboard", ...],
  "fault_type":       "cpu",
  "recorded_at":      "2026-09-09T12:00:00",
  "ticks": [
      {"tick": 0, "anomaly_signals": {"ts-train-service": 0.11, ...}},
      ...
  ]
}

`source` is recorded deliberately: a run marked "synthetic" must never be
reported as a system evaluation. The evaluator refuses to mix the two.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field, asdict
from datetime import datetime
from typing import Dict, List, Optional

SCHEMA_VERSION = 2

# A run whose signals came from Prometheus via the Rectifier + autoencoder.
SOURCE_LIVE = "live"
# A run whose signals were generated by a simulator. Useful for testing the
# pipeline itself; never valid evidence about the system's real performance.
SOURCE_SYNTHETIC = "synthetic"

VALID_SOURCES = (SOURCE_LIVE, SOURCE_SYNTHETIC)


@dataclass
class TickRecord:
    """
    One monitoring tick.

    `anomaly_signals` is what the model sees (per service, from the autoencoder).
    `workload` is what the *user* sees - p95 latency, error rate, request rate -
    and is what src.disruption uses to decide when the failure became visible.
    Keeping both on the same tick is what makes earliness computable.
    """
    tick: int
    anomaly_signals: Dict[str, float]
    workload: Dict[str, float] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "tick": self.tick,
            # Cast to plain float so numpy scalars serialize cleanly.
            "anomaly_signals": {k: float(v) for k, v in self.anomaly_signals.items()},
            "workload": {k: float(v) for k, v in self.workload.items()},
        }

    @staticmethod
    def from_dict(d: dict) -> "TickRecord":
        return TickRecord(
            tick=int(d["tick"]),
            anomaly_signals={k: float(v) for k, v in d["anomaly_signals"].items()},
            # schema v1 files have no workload block
            workload={k: float(v) for k, v in d.get("workload", {}).items()},
        )


@dataclass
class RunRecord:
    """One complete experiment run: healthy throughout, or with one injected fault."""
    run_id: str
    source: str
    is_positive: bool
    services: List[str]
    ticks: List[TickRecord] = field(default_factory=list)
    t_fault: Optional[int] = None
    injected_service: Optional[str] = None
    fault_type: Optional[str] = None
    recorded_at: Optional[str] = None
    # Tick index at which the failure became user-visible, computed by
    # src.disruption from the workload series. None means either a healthy run
    # or a fault that never reached disruption within the recording.
    t_disruption: Optional[int] = None
    # Seconds per tick, needed to report earliness in minutes rather than ticks.
    interval_seconds: float = 60.0
    schema_version: int = SCHEMA_VERSION

    def __post_init__(self):
        if self.source not in VALID_SOURCES:
            raise ValueError(
                f"source must be one of {VALID_SOURCES}, got {self.source!r}"
            )
        if self.recorded_at is None:
            self.recorded_at = datetime.now().isoformat(timespec="seconds")
        self._validate_labels()

    def _validate_labels(self) -> None:
        """A mislabelled run silently corrupts every metric, so fail loudly here."""
        if self.is_positive:
            if self.t_fault is None:
                raise ValueError(f"run {self.run_id}: positive run needs t_fault")
            if self.injected_service is None:
                raise ValueError(f"run {self.run_id}: positive run needs injected_service")
            if self.injected_service not in self.services:
                raise ValueError(
                    f"run {self.run_id}: injected_service {self.injected_service!r} "
                    f"is not in services {self.services}"
                )
        else:
            if self.t_fault is not None or self.injected_service is not None:
                raise ValueError(
                    f"run {self.run_id}: healthy run must not carry t_fault "
                    f"or injected_service"
                )

    def add_tick(self, tick, anomaly_signals, workload=None) -> None:
        self.ticks.append(TickRecord(
            tick=tick,
            anomaly_signals=dict(anomaly_signals),
            workload=dict(workload or {}),
        ))

    def workload_series(self):
        """Per-tick workload dicts, in tick order, for disruption detection."""
        return [t.workload for t in self.ticks]

    def has_workload(self) -> bool:
        return any(t.workload for t in self.ticks)

    def to_dict(self) -> dict:
        d = asdict(self)
        d["ticks"] = [t.to_dict() for t in self.ticks]
        return d

    @staticmethod
    def from_dict(d: dict) -> "RunRecord":
        run = RunRecord(
            run_id=d["run_id"],
            source=d["source"],
            is_positive=bool(d["is_positive"]),
            services=list(d["services"]),
            ticks=[],
            t_fault=d.get("t_fault"),
            injected_service=d.get("injected_service"),
            fault_type=d.get("fault_type"),
            recorded_at=d.get("recorded_at"),
            t_disruption=d.get("t_disruption"),
            interval_seconds=float(d.get("interval_seconds", 60.0)),
            schema_version=int(d.get("schema_version", 1)),
        )
        run.ticks = [TickRecord.from_dict(t) for t in d.get("ticks", [])]
        return run


def save_run(run: RunRecord, directory: str) -> str:
    """Write one run to <directory>/<run_id>.json and return the path."""
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, f"{run.run_id}.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(run.to_dict(), fh, indent=2)
    return path


def load_run(path: str) -> RunRecord:
    with open(path, encoding="utf-8") as fh:
        return RunRecord.from_dict(json.load(fh))


def load_runs(directory: str, source: Optional[str] = None) -> List[RunRecord]:
    """
    Load every run in a directory, sorted by run_id for deterministic ordering.

    Pass `source` to keep only runs from that origin. The evaluator uses this to
    guarantee a reported result never mixes live and synthetic runs.
    """
    if not os.path.isdir(directory):
        return []
    runs = [
        load_run(os.path.join(directory, name))
        for name in sorted(os.listdir(directory))
        if name.endswith(".json")
    ]
    if source is not None:
        runs = [r for r in runs if r.source == source]
    return runs


def summarize(runs: List[RunRecord]) -> str:
    """One-line description of a run set, for printing above any result table."""
    if not runs:
        return "no runs"
    positives = sum(1 for r in runs if r.is_positive)
    sources = sorted({r.source for r in runs})
    ticks = sum(len(r.ticks) for r in runs)
    return (
        f"{len(runs)} runs ({positives} faulty, {len(runs) - positives} healthy), "
        f"{ticks} ticks, source={'+'.join(sources)}"
    )
